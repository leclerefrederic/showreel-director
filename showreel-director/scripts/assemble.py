#!/usr/bin/env python3
"""Assemble a version's main.js from film.json, the scene files and the template. No AI, no network, deterministic.

Usage: python3 assemble.py VERSION_DIR [--out FILE] [--json] [--check] [--force]

A version folder in the scene-file format holds film.json (the montage), scenes/<ID>.js (one file per scene of film.json, named by its ID) and optionally reel.js
(what belongs to the whole film). The assembler puts each scene file, unchanged, in its own zone of main.js ("// >>> scene S01" to "// <<< scene S01"), the reel file
(or neutral defaults) and the template engine/main.assembled.template.js around them. Same inputs, same bytes; changing one scene file changes only its zone.
A scene without a usable file (missing, empty, not valid JavaScript, no return) gets a visible placeholder (an empty frame with its ID) so the film still assembles and
is listed as not generated: in the printed summary, in the JSON on stdout with --json and in VERSION_DIR/assembly.json.
--check exits 1 when main.js is not what the inputs give. main.js is only overwritten when it carries the GENERATED header (a hand-written main.js is never touched
unless --force), so a project in the older single-main.js format keeps building as it is. Contract of the files: references/engine.md, "Scene files".
"""
import argparse, hashlib, json, os, re, shutil, subprocess, sys
sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(HERE, "..", "engine", "main.assembled.template.js")
MARK = "GENERATED by scripts/assemble.py"
ID_OK = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")


def sha(b):
    return hashlib.sha256(b).hexdigest()


def is_assembled(path):
    """True when the file exists and was written by this script."""
    try:
        return MARK in open(path, encoding="utf-8").read(400)
    except OSError:
        return False


def uses_scene_files(vdir):
    """The scene-file format is detected by a scenes/ folder next to film.json; an older version has only main.js."""
    return os.path.isdir(os.path.join(vdir, "scenes"))


def syntax_errors(bodies):
    """{id: message} for the bodies that are not valid JavaScript function bodies; {} and None when node is not there (the check is skipped)."""
    node = shutil.which("node")
    if not node or not bodies:
        return {}, node is not None
    js = ("let s='';process.stdin.on('data',d=>s+=d).on('end',()=>{const b=JSON.parse(s),o={};for(const k of Object.keys(b)){try{new Function(b[k])}catch(e){o[k]=String(e.message).split('\\n')[0]}}console.log(JSON.stringify(o))})")
    r = subprocess.run([node, "-e", js], input=json.dumps(bodies), capture_output=True, text=True)
    if r.returncode != 0:
        return {}, False
    return json.loads(r.stdout or "{}"), True


def load_scene(vdir, sid):
    """(status, body, bytes_sha, size, message). status: module, missing or invalid."""
    if not ID_OK.match(sid):
        return "invalid", None, None, 0, "the scene name %r cannot be a file name" % sid
    p = os.path.join(vdir, "scenes", sid + ".js")
    if not os.path.isfile(p):
        return "missing", None, None, 0, "scenes/%s.js does not exist" % sid
    raw = open(p, "rb").read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return "invalid", None, sha(raw), len(raw), "scenes/%s.js is not UTF-8" % sid
    if not text.strip():
        return "missing", None, sha(raw), len(raw), "scenes/%s.js is empty" % sid
    body = text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"
    if not re.search(r"\breturn\b", body):
        return "invalid", None, sha(raw), len(raw), "scenes/%s.js has no return: it must return the render function" % sid
    return "module", body, sha(raw), len(raw), ""


def assemble(vdir, main="main.js", film="film.json", force=False, write=True):
    """Builds main.js. Returns the result dict (also written as assembly.json). Raises SystemExit with a message on a hard error."""
    fp = os.path.join(vdir, film)
    if not os.path.isfile(fp):
        sys.exit("assemble: %s has no %s (the montage the scenes are assembled from)" % (vdir, film))
    scenes = json.load(open(fp, encoding="utf-8")).get("scenes")
    if not isinstance(scenes, list) or not all(isinstance(s.get("name"), str) for s in scenes):
        sys.exit("assemble: film.json: scenes must be a list of {name, t, ...}")
    ids = [s["name"] for s in scenes]
    if len(set(ids)) != len(ids):
        sys.exit("assemble: film.json lists a scene twice")
    out_path = os.path.join(vdir, main)
    if os.path.exists(out_path) and not is_assembled(out_path) and not force:
        sys.exit("assemble: %s exists and was not written by the assembler (a hand-written main.js is never overwritten). Move it away or delete the scenes/ folder to keep it; --force overwrites it." % out_path)

    loaded = {sid: load_scene(vdir, sid) for sid in ids}
    bodies = {sid: l[1] for sid, l in loaded.items() if l[0] == "module"}
    reel_p = os.path.join(vdir, "reel.js")
    reel_body, reel_state = None, "default"
    if os.path.isfile(reel_p):
        t = open(reel_p, encoding="utf-8").read().replace("\r\n", "\n").rstrip() + "\n"
        if t.strip() and re.search(r"\breturn\b", t):
            reel_body, reel_state = t, "reel.js"
            bodies["__reel__"] = t
        else:
            reel_state = "default (reel.js is empty or has no return)"
    errs, checked = syntax_errors(bodies)
    if "__reel__" in errs:
        reel_body, reel_state = None, "default (reel.js is not valid JavaScript: %s)" % errs["__reel__"]

    zones, report, ungenerated = [], [], []
    for sid in ids:
        status, body, h, size, msg = loaded[sid]
        if status == "module" and sid in errs:
            status, msg = "invalid", "scenes/%s.js is not valid JavaScript: %s" % (sid, errs[sid])
        key = json.dumps(sid)
        if status == "module":
            zones.append("  // >>> scene %s · scenes/%s.js\n  mod(%s, function () {\n%s  });\n  // <<< scene %s\n" % (sid, sid, key, body, sid))
        else:
            ungenerated.append(sid)
            zones.append("  // >>> scene %s · not generated (%s)\n  MODULES[%s] = placeholder(%s, %s);\n  // <<< scene %s\n" % (sid, status, key, key, json.dumps("not generated" if status == "missing" else "invalid: see assembly.json"), sid))
        row = {"id": sid, "file": "scenes/%s.js" % sid, "status": status}
        if h: row.update({"sha256": h, "bytes": size})
        if msg and status != "module": row["message"] = msg
        report.append(row)
    unused = sorted(f[:-3] for f in os.listdir(os.path.join(vdir, "scenes")) if f.endswith(".js") and f[:-3] not in ids) if uses_scene_files(vdir) else []

    tpl = open(TEMPLATE, encoding="utf-8").read()
    text = tpl.replace("/*__SCENES__*/", "".join(zones).rstrip("\n"))
    if reel_body:   # the template holds neutral defaults between the two markers; a reel file takes their place
        text = re.sub(r"/\*__REEL__\*/.*?/\*__END_REEL__\*/", lambda m: "(function () {\n" + reel_body + "})()", text, flags=re.S)
    else:
        text = text.replace("/*__REEL__*/", "").replace("/*__END_REEL__*/", "")
    data = text.encode("utf-8")
    result = {"schema": 1, "main": main, "main_sha256": sha(data), "reel": reel_state, "syntax": "checked" if checked else "skipped (node not found)",
              "scenes": report, "ungenerated": ungenerated, "unused": unused}
    if write:
        if not os.path.exists(out_path) or open(out_path, "rb").read() != data:
            open(out_path, "wb").write(data)
        js = json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        ap = os.path.join(vdir, "assembly.json")
        if not os.path.exists(ap) or open(ap, encoding="utf-8").read() != js:
            open(ap, "w", encoding="utf-8").write(js)
    return result


def summary(r):
    n = len(r["scenes"]); made = n - len(r["ungenerated"])
    s = "assembled %s: %d scene%s, %d from scenes/, reel from %s" % (r["main"], n, "" if n == 1 else "s", made, r["reel"])
    if r["ungenerated"]: s += "\n  not generated (placeholder frame): " + ", ".join(r["ungenerated"])
    for row in r["scenes"]:
        if row["status"] == "invalid": s += "\n  %s: %s" % (row["id"], row.get("message", "invalid"))
    if r["unused"]: s += "\n  scene files that are not in film.json (unused): " + ", ".join(r["unused"])
    if r["syntax"].startswith("skipped"): s += "\n  note: node was not found, so the syntax of the scene files was not checked"
    return s


def main():
    ap = argparse.ArgumentParser(description="Assemble main.js from film.json, scenes/*.js and the template.")
    ap.add_argument("version"); ap.add_argument("--out", help="output file name inside the version folder (default main.js)")
    ap.add_argument("--json", action="store_true", help="print the result as JSON on stdout")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when main.js differs from what the inputs give")
    ap.add_argument("--force", action="store_true", help="overwrite a main.js that the assembler did not write")
    a = ap.parse_args()
    name = a.out or "main.js"
    r = assemble(a.version, main=name, force=a.force, write=not a.check)
    if a.check:
        cur = os.path.join(a.version, name)
        same = os.path.isfile(cur) and sha(open(cur, "rb").read()) == r["main_sha256"]
        print("main.js is up to date" if same else "main.js is out of date: run assemble.py")
        sys.exit(0 if same else 1)
    print(json.dumps(r, indent=2, sort_keys=True, ensure_ascii=False) if a.json else summary(r))


if __name__ == "__main__":
    main()
