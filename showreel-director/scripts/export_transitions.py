#!/usr/bin/env python3
"""Write engine/transitions.js: the scene transitions of the effects lab, packaged for the film layer (engine/film.js).

Usage: python3 export_transitions.py [--check]
The transitions are drawn by engine/effects/14-transitions.js and 22-transitions-more.js, which use the helper block of engine/effects-lab.html
(sceneA, sceneB, W, H, layer, ...). This script wraps that code, unchanged, in one scope and replaces only two things: sceneA and sceneB (the lab
draws stand-in panels, the film layer hands the real outgoing and incoming scenes as off-screen canvases) and the layer() canvas factory (no DOM
needed). Nothing else is copied or rewritten, so a new transition added to the lab is available to films as soon as this script runs.
--check exits 1 when engine/transitions.js is not what this script would write (tools/check.py runs it).
"""
import os, re, sys
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__)); ENG = os.path.join(HERE, "..", "engine")

def build():
    lab = open(os.path.join(ENG, "effects-lab.html"), encoding="utf-8").read()
    a = lab.index("const clamp=(x,a=0,b=1)"); b = lab.index("/*__EFFECTS__*/")
    helper = lab[a:b]
    scenes = re.search(r"function sceneA\(g,c\)\{.*?\}\nfunction sceneB\(g,c\)\{.*?\}\n", helper, re.S)
    if not scenes: sys.exit("effects-lab.html: sceneA/sceneB not found in the helper block")
    helper = helper.replace(scenes.group(0), "// sceneA and sceneB draw the real outgoing and incoming scenes (off-screen canvases set by SRT.draw) into the 640x360 space of the effects\n"
                            "function sceneA(g,c){g.drawImage(_A,0,0,W,H)}\nfunction sceneB(g,c){g.drawImage(_B,0,0,W,H)}\n")
    old = "c=document.createElement('canvas');c.width=W;c.height=H;_lay[id]=c"
    if old not in helper: sys.exit("effects-lab.html: layer() changed, update export_transitions.py")
    helper = helper.replace(old, "c=mkCanvas(W,H);_lay[id]=c")
    if "document" in helper: sys.exit("the helper block still touches the DOM")
    body = "".join(open(os.path.join(ENG, "effects", f), encoding="utf-8").read().rstrip("\n") + "\n" for f in ("14-transitions.js", "22-transitions-more.js"))
    out = ("/* GENERATED by scripts/export_transitions.py from engine/effects-lab.html (helper block) and engine/effects/14-transitions.js + 22-transitions-more.js.\n"
           "   Do not edit: change the lab's transitions and run the script (tools/check.py fails when this file is out of date).\n"
           "   window.SRT: the scene transitions of the catalogue as film transitions. Style-neutral: colours come from the palette the film passes.\n"
           "   SRT.list [{name, desc, energy, dur}], SRT.has(name), SRT.draw(g, name, p, ctx, A, B, SW, SH): draws canvas A (outgoing) and canvas B (incoming), both\n"
           "   SW x SH, mixed at progress p (0..1) into g, with ctx = {P: {bg, fg, accent, accent2}}. */\n"
           "(function (G) {\n'use strict';\n"
           "const mkCanvas = (w, h) => { if (typeof G.SR_CANVAS_FACTORY === 'function') return G.SR_CANVAS_FACTORY(w, h); const c = G.document.createElement('canvas'); c.width = w; c.height = h; return c; };\n"
           "let FONT = 'system-ui,sans-serif', _A = null, _B = null;\n"
           + helper + body +
           "const TCAT = 'Scene transitions', T_ = E.filter(x => x.cat === TCAT);\n"
           "G.SRT = {\n"
           "  list: T_.map(x => ({ name: x.name, desc: x.desc, energy: x.energy, dur: x.dur })),\n"
           "  has: name => T_.some(x => x.name === name),\n"
           "  // The effects draw in a 640x360 space (W x H): the scene canvases are stretched into it and the whole thing is scaled back to the stage, so content keeps its shape.\n"
           "  draw(g, name, p, ctx, A, B, SW, SH) {\n"
           "    const x = T_.find(t => t.name === name); if (!x) throw new Error('unknown transition ' + name);\n"
           "    _A = A; _B = B; g.save(); g.scale(SW / W, SH / H);\n"
           "    try { x.draw(g, Math.min(1, Math.max(0, p)), ctx); } finally { g.restore(); _A = _B = null; }\n"
           "  }\n"
           "};\n})(typeof window !== 'undefined' ? window : globalThis);\n")
    return out

if __name__ == "__main__":
    out = build(); path = os.path.join(ENG, "transitions.js")
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(path) and open(path, encoding="utf-8").read() == out else 1)
    open(path, "w", encoding="utf-8").write(out); print("wrote", os.path.normpath(path))
