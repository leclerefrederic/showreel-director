import CryptoKit
import Foundation

/// brief.md, style-sheet.md and storyboard.md, generated from showreel.json so the skill (in a chat, or through the copilot's file
/// tools) sees the same facts as the app. The app never overwrites one of them silently: see `DocSync`.
public enum ProjectDocs {
    public static let files = ["brief.md", "style-sheet.md", "storyboard.md"]
    public static let header = "<!-- Generated by Showreel Studio from showreel.json. Edit it in the app; changes made here are detected and offered for re-import. -->"

    static func line(_ label: String, _ v: String?) -> String? {
        guard let v = v?.trimmingCharacters(in: .whitespacesAndNewlines), !v.isEmpty else { return nil }
        return "- \(label): \(v)"
    }

    public static func seconds(_ d: Double) -> String { d == d.rounded() ? String(Int(d)) : String(d) }

    /// The generated content of a file, or nil when the project has nothing to say there yet (no empty files are created).
    public static func content(of file: String, from f: ShowreelFile, assets: [AssetRow]) -> String? {
        switch file {
        case "brief.md": return brief(f, assets)
        case "style-sheet.md": return styleSheet(f)
        case "storyboard.md": return storyboard(f)
        default: return nil
        }
    }

    static func brief(_ f: ShowreelFile, _ assets: [AssetRow]) -> String? {
        let p = f.parameters, d = f.decisions
        var out = [header, "", "# Brief: \(f.name)", ""]
        func block(_ title: String, _ lines: [String?]) {
            let l = lines.compactMap { $0 }
            if !l.isEmpty { out += ["## \(title)", ""] + l + [""] }
        }
        func text(_ title: String, _ v: String?) -> [String]? {
            guard let v = v?.trimmingCharacters(in: .whitespacesAndNewlines), !v.isEmpty else { return nil }
            return ["### \(title)", "", v, ""]
        }
        let mission = [text("Audience", p.audience), text("Message", p.message)].compactMap { $0 }.flatMap { $0 }
        if !mission.isEmpty { out += ["## Mission and message", ""] + mission }
        let story = [text("Tone", p.tone)].compactMap { $0 }.flatMap { $0 }
        let langs = [line("Conversation language", f.conversationLanguage), line("Reel languages", f.reelLanguages.joined(separator: ", "))]
        if !story.isEmpty || langs.contains(where: { $0 != nil }) { out += ["## Story and voice", ""] + langs.compactMap { $0 } + (langs.contains { $0 != nil } ? [""] : []) + story }
        block("Look and motion", [
            line("Palette", d.palette?.joined(separator: ", ")), line("Title font", d.fonts?.titles), line("Text font", d.fonts?.text),
            line("Background", [d.background?.id, d.background?.mood.map { "mood \($0)" }].compactMap { $0 }.joined(separator: ", ")),
            line("Moods", d.moods?.joined(separator: ", ")), line("Effects pack", d.effectsPack),
        ])
        block("Sound and delivery", [
            line("Track", [d.track?.file, d.track?.bpm.map { "\(Int($0.rounded())) BPM" }].compactMap { $0 }.joined(separator: ", ")),
            line("Formats", d.formats?.joined(separator: ", ")), line("Duration", d.duration.map { seconds($0) + " s" }),
        ])
        if let c = text("Constraints", p.constraints) { out += ["## Constraints", ""] + c.dropFirst(2) }
        if !assets.isEmpty {
            let rows = assets.map { [$0.file.isEmpty ? "(not embedded) " + $0.original : $0.file, $0.type, $0.scene.isEmpty ? "-" : $0.scene,
                                     $0.status, $0.licenceNote.isEmpty ? "-" : $0.licenceNote, $0.notes.isEmpty ? "-" : $0.notes] }
            out += ["## Assets manifest", "", MarkdownTable(header: ["file", "role", "scene", "status", "licence note", "notes"], rows: rows).render(), ""]
        }
        let gates = ShowreelFile.gateKeys.compactMap { k in f.gates[k].map { "- \(k): \($0)" } }
        if !gates.isEmpty { out += ["## Gates", ""] + gates + [""] }
        guard out.count > 4 else { return nil }
        return out.joined(separator: "\n").trimmingCharacters(in: .newlines) + "\n"
    }

    static func styleSheet(_ f: ShowreelFile) -> String? {
        let d = f.decisions
        let has = d.palette != nil || d.fonts != nil || d.background != nil || d.moods != nil || d.effectsPack != nil || d.track != nil
        guard has else { return nil }
        func v(_ s: String?) -> String { (s?.isEmpty == false ? s! : "(to decide)") }
        let type = [d.fonts?.titles.map { "titles \($0)" }, d.fonts?.text.map { "text \($0)" }].compactMap { $0 }.joined(separator: ", ")
        let motion = [d.moods?.joined(separator: ", "), d.effectsPack.map { "effects pack \($0)" },
                      d.background?.id.map { "background \($0)" + (d.background?.mood.map { " (\($0))" } ?? "") }].compactMap { $0 }.joined(separator: "; ")
        let music = [d.track?.file, d.track?.bpm.map { "\(Int($0.rounded())) BPM" }].compactMap { $0 }.joined(separator: ", ")
        return [header, "", "# Style sheet: \(f.name)", "",
                "1. Intended feeling and emotional arc: " + v(f.parameters.tone),
                "2. Palette: " + v(d.palette?.joined(separator: ", ")),
                "3. Type: " + v(type),
                "4. Motion vocabulary: " + v(motion),
                "5. Energy curve: (to decide)",
                "6. Key moment: (to decide)",
                "7. Music approach: " + v(music), ""].joined(separator: "\n")
    }

    static func storyboard(_ f: ShowreelFile) -> String? {
        guard !f.scenes.isEmpty else { return nil }
        let langs = Array(Set(f.scenes.flatMap { $0.texts.keys })).sorted()
        let extras = Array(Set(f.scenes.flatMap { $0.extra.keys })).sorted()
        let cuts = f.scenes.contains { !$0.inCuts.isEmpty }
        let notes = f.scenes.contains { !$0.note.isEmpty }
        var head = ["ID", "Time", "On-screen text"] + langs + ["Image and motion", "Feeling and tension", "Handoff"] + (cuts ? ["In cuts"] : []) + extras + ["Status"] + (notes ? ["Note"] : [])
        head = head.map { $0 }
        let rows = f.scenes.map { s -> [String] in
            let time: String = (s.start != nil && s.end != nil) ? "\(seconds(s.start!))-\(seconds(s.end!)) s" : ""
            return [s.id, time, s.text] + langs.map { s.texts[$0] ?? "" } + [s.visual, s.feeling, s.handoff] + (cuts ? [s.inCuts] : [])
                + extras.map { s.extra[$0] ?? "" } + [s.status] + (notes ? [s.note] : [])
        }
        return [header, "", "# Storyboard: \(f.name)", "", MarkdownTable(header: head, rows: rows).render(), ""].joined(separator: "\n")
    }

    public static func sha256(_ s: String) -> String {
        SHA256.hash(data: Data(s.utf8)).map { String(format: "%02x", $0) }.joined()
    }
}

/// How each generated file stands against what the app last wrote (hashes in `.studio/generated.json`).
public enum DocState: Equatable, Sendable {
    case notNeeded           // nothing to say there yet
    case inSync
    case created             // the file did not exist: written
    case regenerated         // the file was the app's last version: rewritten
    case edited              // the app wrote it, then it was changed outside the app
    case foreign             // exists, but the app never wrote it (made in a chat)
}

public struct DocReport: Equatable, Sendable {
    public let file: String
    public let state: DocState
    public var needsDecision: Bool { state == .edited || state == .foreign }
}

public enum DocSync {
    static let recordPath = ".studio/generated.json"

    static func hashes(_ store: ProjectStore) -> [String: String] {
        guard let d = try? Data(contentsOf: store.root.appendingPathComponent(recordPath)),
              let h = try? JSONDecoder().decode([String: String].self, from: d) else { return [:] }
        return h
    }

    static func setHash(_ store: ProjectStore, _ file: String, _ value: String) {
        var h = hashes(store)
        h[file] = value
        try? FileManager.default.createDirectory(at: store.root.appendingPathComponent(".studio"), withIntermediateDirectories: true)
        let e = JSONEncoder(); e.outputFormatting = [.prettyPrinted, .sortedKeys]
        try? e.encode(h).write(to: store.root.appendingPathComponent(recordPath), options: .atomic)
    }

    /// Compares every generated file with what the app would write now. Writes the ones that are safe to write (absent, or still the
    /// app's own last version) and reports the ones that need the user's decision. Never overwrites a file changed outside the app.
    @discardableResult
    public static func sync(_ store: ProjectStore) -> [DocReport] {
        guard let f = store.loadShowreel() else { return [] }
        let assets = Assets.load(store)
        let recorded = hashes(store)
        var out: [DocReport] = []
        for file in ProjectDocs.files {
            guard let g = ProjectDocs.content(of: file, from: f, assets: assets) else { out.append(DocReport(file: file, state: .notNeeded)); continue }
            let existing = store.read(file)
            func write(_ s: DocState) -> DocReport {
                if (try? store.write(file, g, source: .user, syncDocs: false)) != nil { setHash(store, file, ProjectDocs.sha256(g)) }
                return DocReport(file: file, state: s)
            }
            guard let e = existing else { out.append(write(.created)); continue }
            if e == g { setHash(store, file, ProjectDocs.sha256(g)); out.append(DocReport(file: file, state: .inSync)); continue }
            guard let h = recorded[file] else { out.append(DocReport(file: file, state: .foreign)); continue }
            out.append(ProjectDocs.sha256(e) == h ? write(.regenerated) : DocReport(file: file, state: .edited))
        }
        return out
    }

    /// The files that need the user's decision (changed outside the app, or never written by it), without writing anything.
    public static func pending(_ store: ProjectStore) -> [DocReport] {
        guard let f = store.loadShowreel() else { return [] }
        let assets = Assets.load(store)
        let recorded = hashes(store)
        var out: [DocReport] = []
        for file in ProjectDocs.files {
            guard let g = ProjectDocs.content(of: file, from: f, assets: assets), let e = store.read(file), e != g else { continue }
            if let h = recorded[file] { if ProjectDocs.sha256(e) != h { out.append(DocReport(file: file, state: .edited)) } }
            else { out.append(DocReport(file: file, state: .foreign)) }
        }
        return out
    }

    /// The user's explicit choice: replace the file with the app's version. The old content stays in the history.
    public static func overwrite(_ store: ProjectStore, _ file: String) throws {
        guard let f = store.loadShowreel(), let g = ProjectDocs.content(of: file, from: f, assets: Assets.load(store)) else { return }
        try store.write(file, g, source: .user, syncDocs: false)
        setHash(store, file, ProjectDocs.sha256(g))
    }

    /// What the markdown says, read back into a showreel: the proposal behind "re-import". Nothing is written.
    public static func reimport(_ store: ProjectStore, files: [String]) -> (proposed: ShowreelFile, changes: [Change])? {
        guard let current = store.loadShowreel() else { return nil }
        var f = current
        let brief = files.contains("brief.md") ? store.read("brief.md") : nil
        let style = files.contains("style-sheet.md") ? store.read("style-sheet.md") : nil
        if let b = brief {
            for (key, title) in [("audience", "Audience"), ("message", "Message"), ("tone", "Tone"), ("constraints", "Constraints")] {
                if let v = MarkdownRead.text(under: title, in: b) ?? MarkdownRead.labelled(title, in: b) {
                    switch key {
                    case "audience": f.parameters.audience = v
                    case "message": f.parameters.message = v
                    case "tone": f.parameters.tone = v
                    default: f.parameters.constraints = v
                    }
                }
            }
        }
        // palette, fonts, languages and duration: the same reading as for a markdown-only project
        let scratch = ProjectImporter.read(brief: brief ?? "", style: style ?? "", name: f.name)
        if brief != nil || style != nil {
            if let p = scratch.decisions.palette { f.decisions.palette = p }
            if let t = scratch.decisions.fonts { f.decisions.fonts = t }
            if !scratch.reelLanguages.isEmpty { f.reelLanguages = scratch.reelLanguages }
            if let d = scratch.decisions.duration { f.decisions.duration = d }
        }
        if files.contains("storyboard.md"), let sb = store.read("storyboard.md"), let scenes = MarkdownRead.scenes(from: sb, keeping: current.scenes) {
            f.scenes = scenes
        }
        return (f, Operations.diff(current, f))
    }

    /// Accepts a re-import: the changed files are adopted as the app's last version, then showreel.json is saved and the files are
    /// regenerated in the app's form (the old content stays in the history).
    public static func acceptReimport(_ store: ProjectStore, files: [String], proposed: ShowreelFile) throws {
        for file in files { if let t = store.read(file) { setHash(store, file, ProjectDocs.sha256(t)) } }
        try store.save(proposed)
    }
}

/// Reading back what `ProjectDocs` writes, and the common ways a chat writes the same facts.
enum MarkdownRead {
    /// The text under a `### Title` (or `## Title`) heading, up to the next heading.
    static func text(under title: String, in md: String) -> String? {
        let lines = md.components(separatedBy: "\n")
        guard let i = lines.firstIndex(where: { $0.hasPrefix("#") && $0.drop(while: { $0 == "#" }).trimmingCharacters(in: .whitespaces).lowercased() == title.lowercased() }) else { return nil }
        var body: [String] = []
        for l in lines[(i + 1)...] { if l.hasPrefix("#") { break }; body.append(l) }
        let t = body.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
        return t.isEmpty ? nil : t
    }

    /// "Audience: ..." on one line, as a chat's brief often has it.
    static func labelled(_ label: String, in md: String) -> String? {
        ProjectImporter.capture(#"^[\s\-*]*"# + label + #"\s*[:=]\s*([^\n]+)"#, in: md)
    }

    static func number(_ s: String) -> [Double] {
        ProjectImporter.matches(#"\d+(?:[.,]\d+)?"#, in: s).compactMap { Double($0.replacingOccurrences(of: ",", with: ".")) }
    }

    /// The first table of a storyboard as scenes. Scenes already in the project keep their review state; an ID that left the table stays,
    /// marked ditched (an ID is never reused).
    static func scenes(from md: String, keeping old: [ShowreelFile.Scene]) -> [ShowreelFile.Scene]? {
        guard let table = MarkdownTable.parse(md).compactMap({ b -> MarkdownTable? in if case .table(let t) = b { return t }; return nil }).first else { return nil }
        func col(_ keys: [String]) -> Int? { table.header.firstIndex { h in keys.contains { h.lowercased().contains($0) } } }
        let cid = table.sceneColumn ?? 0
        let ctime = col(["time", "duration"]), cimg = col(["image", "motion", "visual"]), cfeel = col(["feeling", "tension"])
        let chand = col(["handoff", "gag", "transition"]), ccuts = col(["in cuts", "cuts"]), cstatus = col(["status"]), cnote = col(["note"])
        let ctext = table.header.firstIndex { let h = $0.lowercased(); return h.contains("text") && !h.contains("texts") && h.hasPrefix("on-screen") } ?? col(["text"])
        let known: Set<Int> = Set([cid, ctime, cimg, cfeel, chand, ccuts, cstatus, cnote, ctext].compactMap { $0 })
        var out: [ShowreelFile.Scene] = []
        for r in table.rows {
            func cell(_ c: Int?) -> String { c.flatMap { $0 < r.count ? r[$0] : nil } ?? "" }
            let id = cell(cid).trimmingCharacters(in: .whitespaces)
            guard !id.isEmpty else { continue }
            var s = old.first { $0.id == id } ?? ShowreelFile.Scene(id: id)
            let t = number(cell(ctime))
            if t.count >= 2 { s.start = t[0]; s.end = t[1] }
            s.text = cell(ctext); s.visual = cell(cimg); s.feeling = cell(cfeel); s.handoff = cell(chand); s.inCuts = cell(ccuts)
            if cstatus != nil { let st = cell(cstatus).lowercased(); if ["open", "ok", "modify", "ditched"].contains(st) { s.status = st } }
            if cnote != nil { s.note = cell(cnote) }
            var texts: [String: String] = [:], extra: [String: String] = [:]
            for (i, h) in table.header.enumerated() where !known.contains(i) {
                let v = cell(i)
                if v.isEmpty { continue }
                if s.texts[h] != nil || old.contains(where: { $0.texts[h] != nil }) { texts[h] = v } else { extra[h] = v }
            }
            s.texts = texts.isEmpty ? s.texts.filter { _ in false } : texts
            s.extra = extra
            out.append(s)
        }
        for o in old where !out.contains(where: { $0.id == o.id }) { var d = o; d.status = "ditched"; out.append(d) }
        return out
    }
}
