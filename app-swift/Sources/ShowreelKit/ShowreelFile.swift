import Foundation

/// `showreel.json`, schema version 1: the structured decisions of a project (docs/studio-spec.md, section 3.1).
public struct ShowreelFile: Codable, Equatable {
    public static let fileName = "showreel.json"
    public static let currentSchema = 1

    public struct Fonts: Codable, Equatable {
        public var titles: String?
        public var text: String?
        public init(titles: String? = nil, text: String? = nil) { self.titles = titles; self.text = text }
    }
    public struct Background: Codable, Equatable {
        public var id: String?
        public var mood: String?
        public init(id: String? = nil, mood: String? = nil) { self.id = id; self.mood = mood }
    }
    public struct Track: Codable, Equatable {
        public var file: String?
        public var bpm: Double?
        public init(file: String? = nil, bpm: Double? = nil) { self.file = file; self.bpm = bpm }
    }
    public struct Decisions: Codable, Equatable {
        public var palette: [String]?
        public var fonts: Fonts?
        public var background: Background?
        public var moods: [String]?
        public var effectsPack: String?
        public var formats: [String]?
        public var duration: Double?
        public var track: Track?
        public init() {}
    }
    public struct SceneState: Codable, Equatable {
        public var status: String
        public var note: String
        public init(status: String = "open", note: String = "") { self.status = status; self.note = note }
    }

    public var schema: Int
    public var name: String
    public var created: String
    public var conversationLanguage: String?
    public var reelLanguages: [String]
    public var step: String
    public var decisions: Decisions
    public var gates: [String: String]
    public var scenes: [String: SceneState]

    public init(name: String, created: String = ShowreelFile.today(), conversationLanguage: String? = nil,
                reelLanguages: [String] = [], step: String = "start") {
        self.schema = Self.currentSchema
        self.name = name
        self.created = created
        self.conversationLanguage = conversationLanguage
        self.reelLanguages = reelLanguages
        self.step = step
        self.decisions = Decisions()
        self.gates = [:]
        self.scenes = [:]
    }

    // A hand-edited or copilot-written file may lack keys: every key but the schema falls back to a default.
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        schema = try c.decodeIfPresent(Int.self, forKey: .schema) ?? Self.currentSchema
        name = try c.decodeIfPresent(String.self, forKey: .name) ?? ""
        created = try c.decodeIfPresent(String.self, forKey: .created) ?? Self.today()
        conversationLanguage = try c.decodeIfPresent(String.self, forKey: .conversationLanguage)
        reelLanguages = try c.decodeIfPresent([String].self, forKey: .reelLanguages) ?? []
        step = try c.decodeIfPresent(String.self, forKey: .step) ?? "start"
        decisions = try c.decodeIfPresent(Decisions.self, forKey: .decisions) ?? Decisions()
        gates = try c.decodeIfPresent([String: String].self, forKey: .gates) ?? [:]
        scenes = try c.decodeIfPresent([String: SceneState].self, forKey: .scenes) ?? [:]
    }

    public static func today() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd"
        return f.string(from: Date())
    }

    /// Stable output (sorted keys, indented) so that diffs in the history stay small.
    public func encoded() throws -> String {
        let e = JSONEncoder()
        e.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return String(decoding: try e.encode(self), as: UTF8.self) + "\n"
    }

    public static func decode(_ text: String) throws -> ShowreelFile {
        try JSONDecoder().decode(ShowreelFile.self, from: Data(text.utf8))
    }

    // MARK: Decisions section of brief.md

    public static let sectionStart = "<!-- studio:decisions:start -->"
    public static let sectionEnd = "<!-- studio:decisions:end -->"

    /// The generated block that lets the skill, in a chat, see the same facts as the app.
    public func decisionsSection() -> String {
        var lines = [Self.sectionStart, "## Decisions (generated by Showreel Studio from showreel.json; edit them in the app)", ""]
        let d = decisions
        func add(_ label: String, _ value: String?) { if let v = value, !v.isEmpty { lines.append("- \(label): \(v)") } }
        add("Conversation language", conversationLanguage)
        add("Reel languages", reelLanguages.isEmpty ? nil : reelLanguages.joined(separator: ", "))
        add("Step", step)
        add("Palette", d.palette?.joined(separator: ", "))
        add("Title font", d.fonts?.titles)
        add("Text font", d.fonts?.text)
        add("Background", [d.background?.id, d.background?.mood.map { "mood \($0)" }].compactMap { $0 }.joined(separator: ", "))
        add("Moods", d.moods?.joined(separator: ", "))
        add("Effects pack", d.effectsPack)
        add("Formats", d.formats?.joined(separator: ", "))
        add("Duration", d.duration.map { ($0 == $0.rounded() ? String(Int($0)) : String($0)) + " s" })
        add("Track", [d.track?.file, d.track?.bpm.map { "\(Int($0.rounded())) BPM" }].compactMap { $0 }.joined(separator: ", "))
        for g in gates.keys.sorted() { add("Gate \(g)", gates[g]) }
        lines.append(Self.sectionEnd)
        return lines.joined(separator: "\n")
    }

    /// `brief` with the generated section replaced (or appended when there is none). Idempotent.
    public func applyDecisionsSection(to brief: String) -> String {
        let block = decisionsSection()
        if let a = brief.range(of: Self.sectionStart), let b = brief.range(of: Self.sectionEnd, range: a.upperBound..<brief.endIndex) {
            return brief.replacingCharacters(in: a.lowerBound..<b.upperBound, with: block)
        }
        let body = brief.hasSuffix("\n") || brief.isEmpty ? brief : brief + "\n"
        return body + (body.isEmpty ? "" : "\n") + block + "\n"
    }
}
